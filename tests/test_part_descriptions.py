"""Part descriptions say what the part is, never who made the file (Oliver, 2026-10-20: "ensure parts we generate have
legitimate descriptions and not generated by ecadlib or easy eda").

On his PC the crystals added from the Altium menu came out as "Crystals, CRYSTAL-SMD_L7.0-W4.0-LS7.8" (EasyEDA's tag
and footprint name), their footprints as "From the JLCEDA/EasyEDA Official Library ...; converted by
ecadlib.easyeda_convert; check against the datasheet" and their symbols as "converted from EasyEDA by
ecadlib.easyeda_convert", while LCSC's own text ("-20℃~+70℃ 16MHz 20pF ±10ppm ±30ppm HC-49S-SMD-2P-Mini Crystals
ROHS") was in the triage. The EasyEDA and JLCPCB answers here are REAL (tests/fixtures/easyeda_live/C2975360.json,
C9002.json, tests/fixtures/jlcpcb/C2975360.json). Run:  python -m tests.test_part_descriptions"""
import json, re, tempfile
from pathlib import Path

from ecadlib import altium_lib as AL, easyeda_convert as EC, footprint_gen as F, librarian as L, providers as P, \
    release_check as RC, rules as RU, sexpr
from ecadlib.httpcache import Response
from tests import test_librarian as TL

FIX = Path(__file__).parent / "fixtures"
XTAL16 = json.loads((FIX / "easyeda_live" / "C2975360.json").read_text(encoding="utf-8"))
XTAL12 = json.loads((FIX / "easyeda_live" / "C9002.json").read_text(encoding="utf-8"))
JLC16 = (FIX / "jlcpcb" / "C2975360.json").read_text(encoding="utf-8")
LCSC_TEXT = "-20℃~+70℃ 16MHz 20pF ±10ppm ±30ppm HC-49S-SMD-2P-Mini Crystals ROHS"
FILLER = re.compile(r"ecadlib|easyeda|jlceda|lceda|converted|generated by|review before use", re.I)
MENU_BOM = ("Designator,Qty,Value,Footprint,Manufacturer,Mfr. Part #,LCSC Part Number,Description,Datasheet\n"
            "U1,1,16M 20PF 10PPM,,SOSET,16M 20PF 10PPM,C2975360,,\n")      # as the Altium menu's Add part writes it


class HTTP(TL.FakeHTTP):
    """TL.FakeHTTP plus JLCPCB's parts search (answers for the keywords in `jlc`, else refused as from the cloud)."""
    def __init__(self, easyeda, jlc=None):
        super().__init__(easyeda)
        self.jlc = jlc or {}

    def post(self, url, body, headers=None, **kw):
        self.calls.append(url)
        key = json.loads(body).get("keyword") if url == P.JLCPCBSearch.URL else None
        if key in self.jlc:
            return Response(200, self.jlc[key])
        return Response(403, "", error="HTTP 403")


def _texts(out):
    """Every description the run wrote: Altium SchLib / PcbLib and the KiCad footprints."""
    got = []
    for f in Path(out).rglob("*.SchLib"):
        got += [r.get("COMPONENTDESCRIPTION", "") for s in AL.read_schlib(f)[1] for r in s["records"] if r.get("RECORD") == "1"]
    for f in Path(out).rglob("*.PcbLib"):
        got += [fp["params"].get("DESCRIPTION", "") for fp in AL.read_pcblib(f)]
    for f in Path(out).rglob("*.kicad_mod"):
        got += [(sexpr.first(sexpr.parse(f.read_text(encoding="utf-8")), "descr") or ["", ""])[1]]
    return got


def test_menu_crystal_gets_lcsc_text_not_easyeda_filler():
    with tempfile.TemporaryDirectory() as d:
        items, http = TL.run(d, http=HTTP({"C2975360": XTAL16}, {"C2975360": JLC16}), bom=MENU_BOM,
                             sources=["easyeda"], providers=["jlcpcb_search", "easyeda"])
        it = next(iter(items.values()))
        assert it["description"] == LCSC_TEXT, it["description"]
        assert "LCSC" in it["field_sources"]["Description"], it["field_sources"]
        texts = _texts(Path(d) / "out")
    assert texts and not [t for t in texts if FILLER.search(t)], texts


def test_easyeda_own_text_beats_its_tag_and_footprint_name():
    """JLCPCB refused (as it does from the cloud): EasyEDA's own description text is used; with none, no
    '<tag>, <EasyEDA footprint name>' is made up: the part is held for its Description."""
    bom = MENU_BOM + "U2,1,X322512MSB4SI,,YXC,X322512MSB4SI,C9002,,\n"
    with tempfile.TemporaryDirectory() as d:
        items, _ = TL.run(d, http=HTTP({"C2975360": XTAL16, "C9002": XTAL12}), bom=bom,
                          sources=["easyeda"], providers=["jlcpcb_search", "easyeda"])
        texts = _texts(Path(d) / "out")
    x12 = next(i for i in items.values() if "X322512MSB4SI" in i["name"])
    x16 = next(i for i in items.values() if "16M" in i["name"])
    assert x12["description"] == "YSX321SL 12MHZ 20PF 10PPM -40~+85℃", x12["description"]
    assert x16["description"] == "", x16["description"]
    assert "Description" not in x16["field_sources"], x16["field_sources"]
    assert "fields: Description is empty" in (x16.get("release_check") or {}).get("failures", []), x16.get("release_check")
    assert not [t for t in texts if FILLER.search(t)], texts


def test_parse_easyeda_gives_no_tag_and_package_filler():
    assert "description" not in P.parse_easyeda(XTAL16, P.SourceResult("easyeda")).extra
    assert P.parse_easyeda(XTAL12, P.SourceResult("easyeda")).extra["description"] == "YSX321SL 12MHZ 20PF 10PPM -40~+85℃"


def test_jlcpcb_lookup_by_lcsc_number():
    res = P.JLCPCBSearch(HTTP({}, {"C2975360": JLC16})).lookup_lcsc("C2975360")
    assert res.found and res.lcsc == "C2975360" and res.extra["description"] == LCSC_TEXT, res
    assert not P.JLCPCBSearch(HTTP({}, {"C2975360": JLC16})).lookup_lcsc("C1").found


def test_converted_easyeda_files_describe_the_package_and_keep_the_credit_apart():
    pkg = XTAL16["result"]["packageDetail"]
    fp = EC.footprint_to_kicad(pkg["dataStr"], pkg["title"], [])
    t = sexpr.parse(fp)
    descr = sexpr.first(t, "descr")[1]
    assert not FILLER.search(descr) and "7.0 x 4.0 mm" in descr and "2 pads" in descr, descr
    assert EC.CREDIT in fp                                    # the credit EasyEDA asks for stays in the file, as a field
    sym = EC.symbol_to_kicad(XTAL16["result"]["dataStr"], "X", "", {}, [])
    desc = re.search(r'\(property "Description" "([^"]*)"', sym).group(1)
    assert not FILLER.search(desc), desc
    assert EC.CREDIT in sym


def test_package_words():
    assert EC.package_words("SOIC-8_L4.9-W3.9-P1.27-LS6.0-BL", 8) == "SOIC-8, 4.9 x 3.9 mm body, 1.27 mm pitch, 8 pads"
    assert EC.package_words("CRYSTAL-SMD_L7.0-W4.0-LS7.8", 2) == "CRYSTAL-SMD, 7.0 x 4.0 mm body, 2 pads"
    assert EC.package_words("", 3) == "3 pads"


def test_generated_footprints_say_what_they_are():
    spec = json.loads((L.SPECS / "C_0402_1005Metric.json").read_text())
    txt, rep = F.build(spec)
    descr = sexpr.first(sexpr.parse(txt), "descr")[1]
    assert "IPC-7351B" in descr and not FILLER.search(descr), descr
    fp = AL.footprint_from_spec(spec)[0]
    assert "IPC-7351B" in fp["description"] and not FILLER.search(fp["description"]), fp["description"]


def test_no_description_is_left_empty_and_held():
    """Nothing is made up from the category and package ("IC, C2975360" for a crystal on Oliver's PC): the part is
    held for its Description, which a person types (or releases anyway)."""
    item = {"name": "X1", "folder": "Components/ICs", "description": "", "footprint": {"ref": "X1"}, "symbol": {},
            "parameters": [{"name": "Manufacturer", "value": "SOSET"}, {"name": "Manufacturer Part Number", "value": "X1"}]}
    L.apply_state(item, {"found": {"package": ("CRYSTAL-SMD_L7.0-W4.0-LS7.8", "EasyEDA C2975360")}}, {"mpn": "X1"})
    assert item["description"] == "" and "Description" not in item["field_sources"], item
    fails, _, _ = RC.check_item(item, ".", RU.resolve(None, "."))
    assert ("fields", "Description is empty") in fails, fails


def test_a_passive_is_described_from_its_own_bom_line():
    """A 10k 0603 resistor built offline from the standard tables: its BOM line's value, tolerance and package in a
    distributor's words, not '<category>, <package>, <MPN>'. Only passives: they are their value and size."""
    item = {"name": "R1", "folder": "Components/Resistors", "description": "", "symbol": {},
            "footprint": {"ref": "R_0603", "kicad": "Resistor_SMD:R_0603_1608Metric"},
            "parameters": [{"name": "Value", "value": "10k"}, {"name": "Manufacturer Part Number", "value": "RC0603FR-0710KL"}]}
    L.apply_state(item, {"found": {}}, {"value": "10k", "description": "", "tolerance": "", "mpn": "RC0603FR-0710KL"})
    assert item["description"] == "RES 10kΩ 0603", item["description"]
    assert item["field_sources"]["Description"] == "the BOM line's value and package"
    cap = {"folder": "Components/Capacitors", "parameters": [], "footprint": {}}
    assert L.passive_description(cap, {}, {"value": "100nF 16V X7R", "footprint": "C_0402_1005Metric"}) == "CAP 100nF 16V X7R 0402"
    assert L.passive_description({"folder": "Components/ICs", "parameters": [], "footprint": {}}, {}, {"value": "10k"}) == ""


def test_no_source_file_writes_tool_names_into_descriptions():
    """A guard: the phrases that used to end up in part, symbol and footprint descriptions."""
    src = Path(__file__).parent.parent / "ecadlib"
    bad = re.compile(r"generated by ecadlib \(prototype|converted by ecadlib\.easyeda_convert|converted from EasyEDA by|"
                     r"read from the datasheet by ecadlib|; generated by ecadlib\"|written by ecadlib from the part")
    hits = [f"{f.name}:{n}" for f in src.rglob("*.py") for n, ln in enumerate(f.read_text(encoding="utf-8").splitlines(), 1)
            if bad.search(ln)]
    assert not hits, hits


