"""`ecadlib completion bash|zsh|fish`: a shell completion script generated from the commands' own argparse parsers,
so it always matches this version (commands, subcommands, options, fixed choices).

    mkdir -p ~/.local/share/bash-completion/completions && ecadlib completion bash > ~/.local/share/bash-completion/completions/ecadlib
    ecadlib completion zsh  > "${fpath[1]}/_ecadlib"          (or: source <(ecadlib completion zsh))
    mkdir -p ~/.config/fish/completions && ecadlib completion fish > ~/.config/fish/completions/ecadlib.fish

Each command's parser is captured by running its main() with parse_args replaced by a stub that stops at once, so
nothing is read, written or fetched. A command whose parser cannot be captured still completes by name."""
import argparse, contextlib, importlib, io, sys

GLOBAL = ["-h", "--help", "-V", "--version", "--debug"]


class _Got(Exception):
    def __init__(self, parser):
        self.parser = parser


def _capture(target):
    """The ArgumentParser `target` ("module" or "module:function") builds in its main(), or None."""
    mod, _, fn = target.partition(":")
    orig = (argparse.ArgumentParser.parse_args, argparse.ArgumentParser.parse_known_args)

    def stop(self, *a, **k):
        raise _Got(self)
    argparse.ArgumentParser.parse_args = argparse.ArgumentParser.parse_known_args = stop
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            getattr(importlib.import_module(mod), fn or "main")([])
    except _Got as g:
        return g.parser
    except BaseException:                         # no argparse, or main() needs more: complete the name only
        return None
    finally:
        argparse.ArgumentParser.parse_args, argparse.ArgumentParser.parse_known_args = orig
    return None


def describe(parser):
    """{"options": [...], "choices": {option: [...]}, "subcommands": {name: describe(sub)}, "positional_choices": [...]}"""
    out = {"options": [], "value_options": [], "choices": {}, "subcommands": {}, "positional_choices": []}
    if parser is None:
        return out
    for act in parser._actions:
        if isinstance(act, argparse._SubParsersAction):
            for name, sub in act.choices.items():
                out["subcommands"][name] = describe(sub)
        elif act.option_strings:
            names = [o for o in act.option_strings if o.startswith("--") or len(o) == 2]
            out["options"] += names
            if act.nargs != 0:
                out["value_options"] += names
            if act.choices:
                for o in act.option_strings:
                    out["choices"][o] = [str(c) for c in act.choices]
        elif act.choices:
            out["positional_choices"] += [str(c) for c in act.choices]
    return out


def tree(commands=None):
    from .cli import COMMANDS
    commands = COMMANDS if commands is None else commands
    out = {}
    for name, (target, help_) in commands.items():
        d = describe(_capture(target)) if name != "completion" else describe(None)
        if name == "completion":
            d["positional_choices"] = list(SHELLS)
        d["help"] = help_
        out[name] = d
    return out


def _words(xs):
    return " ".join(sorted(set(xs)))


def bash(t):
    L = ["# bash completion for ecadlib (generated by `ecadlib completion bash`)",
         "_ecadlib() {",
         '    local cur prev cmd ci sub i',
         '    cur="${COMP_WORDS[COMP_CWORD]}"',
         '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
         '    cmd=""; ci=0; sub=""',
         '    for ((i=1; i<COMP_CWORD; i++)); do',
         '        case "${COMP_WORDS[i]}" in -*) continue;; esac',
         '        cmd="${COMP_WORDS[i]}"; ci=$i; break',
         '    done',
         '    if [[ -z "$cmd" ]]; then',
         f'        COMPREPLY=( $(compgen -W "{_words(list(t) + GLOBAL)}" -- "$cur") ); return 0',
         '    fi',
         '    local opts="" choices=""',
         '    case "$cmd" in']
    for name, d in t.items():
        L.append(f"    {name})")
        if d["subcommands"]:
            names = "|".join(sorted(d["subcommands"]))
            L.append(f'        for ((i=ci+1; i<COMP_CWORD; i++)); do case "${{COMP_WORDS[i]}}" in {names}) sub="${{COMP_WORDS[i]}}"; break;; esac; done')
        for opt, ch in d["choices"].items():
            L.append(f'        [[ "$prev" == "{opt}" ]] && {{ COMPREPLY=( $(compgen -W "{_words(ch)}" -- "$cur") ); return 0; }}')
        if d["subcommands"]:
            L.append('        case "$sub" in')
            for sn, sd in d["subcommands"].items():
                L.append(f"        {sn})")
                for opt, ch in sd["choices"].items():
                    L.append(f'            [[ "$prev" == "{opt}" ]] && {{ COMPREPLY=( $(compgen -W "{_words(ch)}" -- "$cur") ); return 0; }}')
                L.append(f'            opts="{_words(sd["options"] + d["options"])}"; choices="{_words(sd["positional_choices"])}";;')
            L.append(f'        *) opts="{_words(d["options"])}"; choices="{_words(list(d["subcommands"]) + d["positional_choices"])}";;')
            L.append("        esac;;")
        else:
            L.append(f'        opts="{_words(d["options"])}"; choices="{_words(d["positional_choices"])}";;')
    L += ['    esac',
          '    if [[ "$cur" == -* ]]; then',
          '        COMPREPLY=( $(compgen -W "$opts --debug" -- "$cur") )',
          '    elif [[ -n "$choices" ]]; then',
          '        COMPREPLY=( $(compgen -W "$choices" -- "$cur") )',
          '    else',
          '        COMPREPLY=( $(compgen -f -- "$cur") )',
          '    fi',
          '    return 0',
          '}',
          'complete -o filenames -o bashdefault -F _ecadlib ecadlib']
    return "\n".join(L) + "\n"


def zsh(t):
    """zsh runs the bash function through bashcompinit (ships with zsh), so both shells complete the same way."""
    return ("#compdef ecadlib\n# zsh completion for ecadlib (generated by `ecadlib completion zsh`)\n"
            "autoload -U +X bashcompinit && bashcompinit\n" + bash(t).split("\n", 1)[1])


def _fq(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish(t):
    L = ["# fish completion for ecadlib (generated by `ecadlib completion fish`)",
         "complete -c ecadlib -f",
         "complete -c ecadlib -l debug -d 'show tracebacks'",
         "complete -c ecadlib -n __fish_use_subcommand -s V -l version -d 'print the version'"]
    for name, d in t.items():
        L.append(f"complete -c ecadlib -n __fish_use_subcommand -a {name} -d {_fq(d['help'][:80])}")
        cond = f"'__fish_seen_subcommand_from {name}'"
        if d["subcommands"]:
            subs = " ".join(d["subcommands"])
            L.append(f"complete -c ecadlib -n \"__fish_seen_subcommand_from {name}; and not __fish_seen_subcommand_from {subs}\" "
                     f"-a {_fq(subs)}")
        if d["positional_choices"]:
            L.append(f"complete -c ecadlib -n {cond} -a {_fq(' '.join(d['positional_choices']))}")
        opts = set(d["options"]) | {o for sd in d["subcommands"].values() for o in sd["options"]}
        for o in sorted(opts):
            flag = f"-l {o[2:]}" if o.startswith("--") else f"-s {o[1:]}"
            ch = d["choices"].get(o) or next((sd["choices"][o] for sd in d["subcommands"].values() if o in sd["choices"]), None)
            takes = o in d["value_options"] or any(o in sd["value_options"] for sd in d["subcommands"].values())
            L.append(f"complete -c ecadlib -n {cond} {flag}" + (f" -x -a {_fq(' '.join(ch))}" if ch else " -r -F" if takes else ""))
        L.append(f"complete -c ecadlib -n {cond} -F")
    return "\n".join(L) + "\n"


SHELLS = {"bash": bash, "zsh": zsh, "fish": fish}


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ecadlib completion", description="print a shell completion script")
    ap.add_argument("shell", choices=list(SHELLS))
    a = ap.parse_args(argv)
    sys.stdout.write(SHELLS[a.shell](tree()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
